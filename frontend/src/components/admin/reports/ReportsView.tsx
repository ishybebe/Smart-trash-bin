'use client';

import { useCallback, useEffect, useState } from 'react';
import { api } from '@/lib/api';
import { ADMIN_TOKEN_KEY } from '@/lib/adminSession';
import { ReportUtility } from './ReportUtility';
import { AuditLogTable } from './AuditLogTable';
import { ReportPreview } from './ReportPreview';

interface ReportsViewProps {
  onAuthFailure: () => void;
}

interface ReportSummary {
  total_detected: number;
  accepted_recyclables: number;
  points_generated: number;
  packs_redeemed: number;
  points_redeemed: number;
  rice_kg_distributed: number;
}

interface WasteRankingEntry {
  type: string;
  quantity: number;
  points_generated: number;
}

interface ReportData {
  summary: ReportSummary;
  waste_ranking: WasteRankingEntry[];
}

interface GeneratedReport {
  report_id: string;
  created_at: string;
  created_by_admin: string;
  reports: ReportData;
}

export function ReportsView({ onAuthFailure }: ReportsViewProps) {
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState<string | null>(null);
  const [currentReport, setCurrentReport] = useState<GeneratedReport | null>(null);
  const [auditLog, setAuditLog] = useState<GeneratedReport[]>([]);
  const [auditPage, setAuditPage] = useState(1);

  const loadAuditLog = useCallback(async () => {
    const token = window.localStorage.getItem(ADMIN_TOKEN_KEY);
    if (!token) return;
    const response = await api<GeneratedReport[]>('/api/admin/reports/audit', {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (response.success && response.data) {
      setAuditLog(response.data);
      setAuditPage(1);
    }
  }, []);

  const generateReport = useCallback(async () => {
    const token = window.localStorage.getItem(ADMIN_TOKEN_KEY);
    if (!token || busy) return;

    setBusy(true);
    setMessage(null);
    const response = await api<GeneratedReport>('/api/admin/reports', {
      headers: { Authorization: `Bearer ${token}` },
    });

    if (response.error?.code === 'UNAUTHORIZED' || response.error?.code === 'FORBIDDEN' || response.error?.code === 'INVALID_TOKEN' || response.error?.code === 'ACCOUNT_DISABLED') {
      onAuthFailure();
      setBusy(false);
      return;
    }

    if (!response.success || !response.data) {
      setMessage(response.error?.message ?? 'Could not generate the report.');
      setBusy(false);
      return;
    }

    const newReport = response.data;
    setCurrentReport(newReport);
    await loadAuditLog();
    setMessage(`Report ${newReport.report_id} generated by ${newReport.created_by_admin} at ${new Date(newReport.created_at).toLocaleString()}.`);
    setBusy(false);
  }, [busy, onAuthFailure, loadAuditLog]);

  const downloadReport = useCallback(() => {
    if (!currentReport) return;
    window.print();
  }, [currentReport]);

  useEffect(() => {
    // eslint-disable-next-line react-hooks/set-state-in-effect -- initial data fetch on mount
    loadAuditLog();
  }, [loadAuditLog]);

  return (
    <>
      <style jsx>{`
        @media print {
          .print-report-actions,
          .print-report-actions + p,
          [aria-label="Generated reports audit log"],
          .print-report-content > header + section:last-of-type + section + section {
            display: none !important;
          }
          @page {
            size: A4;
            margin: 0;
          }
          .print-report-content {
            width: 210mm;
            min-height: 297mm;
            padding: 20mm;
            box-sizing: border-box;
            margin: 0 auto;
            background: white;
          }
          section[aria-label="Report preview"] {
            border: none !important;
            box-shadow: none !important;
          }
        }
      `}</style>
      <main className="mx-auto w-full max-w-[1400px] space-y-6 px-4 py-10 sm:px-6 lg:px-8">
        <div className="grid min-w-0 gap-6 lg:grid-cols-[minmax(0,1.2fr)_minmax(0,1fr)]">
          <div className="min-w-0 space-y-6">
            <section className="border border-rule bg-paper">
              <div className="border-b border-rule px-5 py-5 sm:px-6">
                <p className="font-data text-[10px] uppercase tracking-[0.24em] text-muted">
                  Report utility
                </p>
                <h1 className="mt-2 font-display text-3xl font-extrabold tracking-[-0.02em] text-ink">
                  Generate report
                </h1>
                <p className="mt-2 text-sm leading-relaxed text-muted">
                  Create a snapshot of detected recyclables, points movement, waste
                  ranking, and physical rice volume from the transaction ledger.
                </p>
              </div>

              <ReportUtility
                busy={busy}
                currentReport={currentReport}
                onGenerate={generateReport}
                onDownload={downloadReport}
                message={message}
              />
            </section>

            <section className="border border-rule bg-paper" aria-label="Generated reports audit log">
              <div className="border-b border-rule px-5 py-4 sm:px-6">
                <p className="font-data text-[10px] uppercase tracking-[0.24em] text-muted">
                  Audit log
                </p>
                <h2 className="mt-1 font-display text-xl font-bold text-ink">
                  Generated reports
                </h2>
              </div>

              <AuditLogTable
                auditLog={auditLog}
                currentPage={auditPage}
                onPageChange={setAuditPage}
              />
            </section>
          </div>

          <ReportPreview currentReport={currentReport} />
        </div>
      </main>
    </>
  );
}
