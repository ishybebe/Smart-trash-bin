'use client';

interface GeneratedReport {
  report_id: string;
  created_at: string;
  created_by_admin: string;
  reports: {
    summary: {
      total_detected: number;
      accepted_recyclables: number;
      points_generated: number;
      packs_redeemed: number;
      points_redeemed: number;
      rice_kg_distributed: number;
    };
    waste_ranking: Array<{
      type: string;
      quantity: number;
      points_generated: number;
    }>;
  };
}

interface ReportPreviewProps {
  currentReport: GeneratedReport | null;
}

export function ReportPreview({ currentReport }: ReportPreviewProps) {
  const report = currentReport ?? {
    report_id: 'Pending snapshot',
    created_at: '',
    created_by_admin: 'Not generated',
    reports: {
      summary: {
        total_detected: 0,
        accepted_recyclables: 0,
        points_generated: 0,
        packs_redeemed: 0,
        points_redeemed: 0,
        rice_kg_distributed: 0,
      },
      waste_ranking: [],
    },
  };

  const formatDate = (iso: string) => iso ? new Date(iso).toLocaleString() : 'Awaiting first snapshot';

  return (
    <section className="min-w-0 w-full max-w-[210mm] border border-rule bg-white" aria-label="Report preview">
      <div className="print-report-content w-full min-w-0 p-5 sm:p-8" style={{ boxSizing: 'border-box', margin: '0 auto' }}>
        <header className="mb-6 border-b border-ink pb-4">
          <p className="font-data text-[10px] uppercase tracking-[0.2em] text-muted">
            Smart Bin · Rice Vendo
          </p>
          <h1 className="mt-1 font-display text-2xl font-extrabold text-ink">
            Operational Report
          </h1>
          <p className="mt-2 font-data text-sm text-muted">
              Report ID: <span className="font-mono">{report.report_id}</span>
          </p>
          <p className="font-data text-sm text-muted">
            Generated by {report.created_by_admin} at {formatDate(report.created_at)}
          </p>
        </header>

        <section className="mb-6">
          <p className="font-data text-[10px] uppercase tracking-[0.2em] text-muted mb-3">
            Summary Metrics
          </p>
          <div className="grid grid-cols-2 gap-3 sm:grid-cols-3 text-sm">
            {[
              ['Total Detected', report.reports.summary.total_detected],
              ['Accepted', report.reports.summary.accepted_recyclables],
              ['Points Issued', report.reports.summary.points_generated],
              ['Packs Dispensed', report.reports.summary.packs_redeemed],
              ['Points Redeemed', report.reports.summary.points_redeemed],
              ['Rice Volume', `${report.reports.summary.rice_kg_distributed} kg`],
            ].map(([label, value]) => (
              <div key={label} className="border border-rule p-3 bg-zinc-50">
                <p className="font-data text-[9px] uppercase tracking-[0.14em] text-muted">{label}</p>
                <p className="mt-1 font-display text-xl font-extrabold tabular-nums text-ink">{value}</p>
              </div>
            ))}
          </div>
        </section>

        <section className="mb-6">
          <p className="font-data text-[10px] uppercase tracking-[0.2em] text-muted mb-3">
            Waste Breakdown
          </p>
          <div className="min-w-0 overflow-x-auto border border-rule">
            <table className="w-full min-w-[420px] border-collapse text-sm">
              <thead>
                <tr className="border-b border-ink bg-zinc-50 font-data text-[9px] uppercase tracking-[0.12em] text-muted">
                  <th className="py-2 px-3 text-left">Material</th>
                  <th className="py-2 px-3 text-right tabular-nums">Quantity</th>
                  <th className="py-2 px-3 text-right tabular-nums">Points</th>
                </tr>
              </thead>
              <tbody>
                {report.reports.waste_ranking.length > 0 ? (
                  report.reports.waste_ranking.map((row) => (
                    <tr key={row.type} className="border-b border-rule">
                      <td className="py-2 px-3 text-ink">{row.type}</td>
                      <td className="py-2 px-3 text-right font-data tabular-nums text-ink">{row.quantity}</td>
                      <td className="py-2 px-3 text-right font-data tabular-nums text-ink">{row.points_generated}</td>
                    </tr>
                  ))
                ) : (
                  <tr>
                    <td colSpan={3} className="py-8 px-3 text-center text-muted">
                      No waste data recorded
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>
        </section>

        <section>
          <p className="font-data text-[10px] uppercase tracking-[0.2em] text-muted mb-3">
            Transaction Ledger
          </p>
          <div className="border border-rule p-3 bg-zinc-50 text-xs text-muted">
            Transaction details available in database audit tables.
          </div>
        </section>
      </div>
    </section>
  );
}
