'use client';

import { Pagination } from './Pagination';

interface GeneratedReport {
  report_id: string;
  created_at: string;
  created_by_admin: string;
  reports: {
    summary: {
      total_detected: number;
      accepted_recyclables: number;
      points_generated: number;
      packs_redeemed: number;
      points_redeemed: number;
      rice_kg_distributed: number;
    };
    waste_ranking: Array<{
      type: string;
      quantity: number;
      points_generated: number;
    }>;
  };
}

interface AuditLogTableProps {
  auditLog: GeneratedReport[];
  currentPage: number;
  onPageChange: (page: number) => void;
}

const ROWS_PER_PAGE = 10;

export function AuditLogTable({ auditLog, currentPage, onPageChange }: AuditLogTableProps) {
  const totalPages = Math.ceil(auditLog.length / ROWS_PER_PAGE);
  const paginatedAuditLog = auditLog.slice((currentPage - 1) * ROWS_PER_PAGE, currentPage * ROWS_PER_PAGE);

  const formatDate = (iso: string) => new Date(iso).toLocaleString();

  return (
    <div className="overflow-x-auto">
      <table className="w-full border-collapse text-left text-sm">
        <thead>
          <tr className="border-b border-ink font-data text-[10px] uppercase tracking-[0.12em] text-muted">
            <th className="py-3 px-4">Report ID</th>
            <th className="py-3 px-4">Generated by</th>
            <th className="py-3 px-4">Timestamp</th>
          </tr>
        </thead>
        <tbody>
          {paginatedAuditLog.length === 0 ? (
            <tr>
              <td colSpan={3} className="py-8 px-4 text-center text-muted">
                No reports generated yet
              </td>
            </tr>
          ) : (
            paginatedAuditLog.map((report) => (
              <tr key={report.report_id} className="border-b border-rule hover:bg-zinc-50">
                <td className="py-3 px-4 font-data tabular-nums text-ink">
                  {report.report_id}
                </td>
                <td className="py-3 px-4 text-ink">
                  {report.created_by_admin}
                </td>
                <td className="py-3 px-4 font-data tabular-nums text-muted">
                  {formatDate(report.created_at)}
                </td>
              </tr>
            ))
          )}
        </tbody>
      </table>
      <Pagination currentPage={currentPage} totalPages={totalPages} onPageChange={onPageChange} />
    </div>
  );
}